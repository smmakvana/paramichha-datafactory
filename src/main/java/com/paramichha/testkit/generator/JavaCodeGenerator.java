package com.paramichha.testkit.generator;

import com.paramichha.testkit.GenerationResult;
import com.paramichha.testkit.ProjectType;
import com.paramichha.testkit.CodeGenerator;
import com.paramichha.testkit.TestKitTemplate;
import com.paramichha.testkit.model.ReflectionClassInfo;
import com.paramichha.testkit.model.ReflectionFieldInfo;
import com.paramichha.testkit.model.ReflectionMethodInfo;
import com.paramichha.testkit.model.TestData;

import com.paramichha.testkit.utils.TestNames;
import com.paramichha.testkit.utils.JavaNames;
import java.util.ArrayList;
import java.util.List;

/**
 * Orchestrates generation — delegates each section to a focused writer.
 * If DataFactory failed, writes a placeholder file with error comment.
 * Never throws — always produces a GeneratedTestClass.
 */
public final class JavaCodeGenerator implements CodeGenerator {

    public static final JavaCodeGenerator INSTANCE = new JavaCodeGenerator(
            DefaultValueExtractor.INSTANCE);

    private ProjectType projectType = ProjectType.detect();

    @Override
    public List<GenerationResult> generateAll(ReflectionClassInfo meta, TestData data,
                                              String targetPackage, TestKitTemplate template,
                                              ProjectType projectType) {
        this.projectType = projectType;
        return generateAll(meta, data, targetPackage, template);
    }

    @Override
    public List<GenerationResult> generateAll(ReflectionClassInfo meta, TestData data,
                                              String targetPackage, TestKitTemplate template) {
        if (data.hasError()) {
            return List.of(new GenerationResult(
                    meta.simpleName() + "Test", targetPackage,
                    "// Generation failed: " + data.error()));
        }
        try {
            return buildSplit(meta, data, targetPackage, template);
        } catch (Exception e) {
            return List.of(new GenerationResult(
                    meta.simpleName() + "Test", targetPackage,
                    "// Generation failed: " + e.getMessage()));
        }
    }

    private List<GenerationResult> buildSplit(ReflectionClassInfo meta, TestData data,
                                              String targetPackage, TestKitTemplate template) {
        Class<?> type = data.type();
        String className = meta.simpleName();
        String fieldName = TestNames.toVariable(className);
        List<Object> parts = valueExtractor.extract(data.base(), type, meta.fields());
        InstantiationWriter inst = new InstantiationWriter(meta);
        boolean hasJakarta = projectType.hasValidator();
        String baseName = className + "Test";
        List<GenerationResult> files = new ArrayList<>();

        // ── 1. Base class ─────────────────────────────────────────────────
        StringBuilder base = new StringBuilder();
        base.append("// Generated by TestKit — do not edit by hand.\n");
        base.append("package ").append(targetPackage).append(";\n\n");
        addImports(base, meta, type, parts);
        base.append("\n@DisplayName(\"").append(className).append("\")\n");
        base.append("class ").append(baseName).append(" {\n\n");
        if (hasJakarta) {
            base.append("    private static Validator ").append(template.validatorField).append(";\n\n");
            base.append("    @BeforeAll\n");
            base.append("    static void ").append(template.validatorSetup).append("() {\n");
            base.append("        ").append(template.validatorField)
                    .append(" = Validation.buildDefaultValidatorFactory().getValidator();\n");
            base.append("    }\n\n");
        }
        base.append("    ").append(className).append(" ").append(fieldName)
                .append(" =\n            ").append(inst.constructorCall(parts)).append(";\n\n");
        base.append("}\n");
        files.add(new GenerationResult(baseName, targetPackage, base.toString()));

        // ── 2. Creation file ──────────────────────────────────────────────
        String creationName = template.resolve(template.creationClassName, className, "");
        StringBuilder cr = new StringBuilder();
        cr.append("// Generated by TestKit — do not edit by hand.\n");
        cr.append("package ").append(targetPackage).append(";\n\n");
        addImports(cr, meta, type, parts);
        cr.append("\n@DisplayName(\"")
                .append(template.resolve(template.creationDisplay, className, "")).append("\")\n");
        cr.append("class ").append(creationName)
                .append(" extends ").append(baseName).append(" {\n\n");
        new CreationTestWriter(meta, inst, template).writeFlat(cr, data, parts, valueExtractor);
        cr.append("}\n");
        files.add(new GenerationResult(creationName, targetPackage, cr.toString()));

        // ── 3. One file per field ─────────────────────────────────────────
        MemberTestWriter mw = new MemberTestWriter(meta, inst, valueExtractor, template);
        List<ReflectionFieldInfo> fields = meta.fields();
        for (int i = 0; i < fields.size(); i++) {
            ReflectionFieldInfo field = fields.get(i);
            String memberName = template.resolve(template.memberClassName, className, field.name());
            StringBuilder mb = new StringBuilder();
            mb.append("// Generated by TestKit — do not edit by hand.\n");
            mb.append("package ").append(targetPackage).append(";\n\n");
            addImports(mb, meta, type, parts);
            mb.append("\n@DisplayName(\"")
                    .append(template.resolve(template.memberDisplay, className, field.name()))
                    .append("\")\n");
            mb.append("class ").append(memberName)
                    .append(" extends ").append(baseName).append(" {\n\n");
            mw.writeFlat(mb, type, parts, field, i);
            mb.append("}\n");
            files.add(new GenerationResult(memberName, targetPackage, mb.toString()));
        }

        // ── 4. One file per method ───────────────────────────────────────
        MethodTestWriter methodWriter2 = new MethodTestWriter(meta, inst, template);
        for (ReflectionMethodInfo method : meta.methods()) {
            String methodClassName = template.resolveMethod(template.methodClassName, className, method.name());
            StringBuilder mm = new StringBuilder();
            mm.append("// Generated by TestKit — do not edit by hand.\n");
            mm.append("package ").append(targetPackage).append(";\n\n");
            addImports(mm, meta, type, parts);
            mm.append("\n@DisplayName(\"")
                    .append(template.resolveMethod(template.methodDisplay, className, method.name()))
                    .append("\"\n");
            mm.append("class ").append(methodClassName)
                    .append(" extends ").append(baseName).append(" {\n\n");
            methodWriter2.writeFlat(mm, method, parts, hasJakarta);
            mm.append("}\n");
            files.add(new GenerationResult(methodClassName, targetPackage, mm.toString()));
        }

        return List.copyOf(files);
    }

    private void addImports(StringBuilder sb, ReflectionClassInfo meta, Class<?> type,
                            List<Object> parts) {
        ImportCollector ic = new ImportCollector();
        ic.addTypeImport(type);
        ic.addFieldTypeImports(meta.fields());
        ic.addValueImports(parts);
        meta.methods().forEach(m -> ic.addAnnotationImports(m.returnType().annotations()));
        boolean needsDataValidation = meta.methods().stream().anyMatch(m ->
                m.returnType().isConstrained() ||
                        m.parameters().stream().anyMatch(p -> !p.validations().isEmpty()));
        if (needsDataValidation) {
            ic.addRawImport("com.paramichha.utils.DataValidation");
        }
        for (String imp : ic.collect()) {
            sb.append("import ").append(imp).append(";\n");
        }
    }


    private final ValueExtractor valueExtractor;

    JavaCodeGenerator(ValueExtractor valueExtractor) {
        this.valueExtractor = valueExtractor;
    }

    @Override
    public GenerationResult generate(ReflectionClassInfo meta, TestData data,
                                     String targetPackage, TestKitTemplate template,
                                     ProjectType projectType) {
        this.projectType = projectType;
        return generateWithTemplate(meta, data, targetPackage, template);
    }

    @Override
    public GenerationResult generate(ReflectionClassInfo meta, TestData data,
                                     String targetPackage, TestKitTemplate template) {
        return generateWithTemplate(meta, data, targetPackage, template);
    }

    @Override
    public GenerationResult generate(ReflectionClassInfo meta, TestData data, String targetPackage) {
        return generateWithTemplate(meta, data, targetPackage, TestKitTemplate.DEFAULT);
    }

    private GenerationResult generateWithTemplate(ReflectionClassInfo meta, TestData data,
                                                  String targetPackage, TestKitTemplate template) {
        // DEV mode gets a distinct class name so both files coexist
        boolean isDev = data.mode() == com.paramichha.datafactory.GenerationMode.DEV;
        String className = isDev
                ? meta.simpleName() + "DevTest"
                : meta.simpleName() + "Test";

        if (data.hasError()) {
            return new GenerationResult(className, targetPackage,
                    buildPlaceholder(meta, targetPackage, data.error(), className));
        }

        try {
            return buildFull(meta, data, targetPackage, className, isDev, template);
        } catch (Exception e) {
            return new GenerationResult(className, targetPackage,
                    buildPlaceholder(meta, targetPackage, e.getMessage(), className));
        }
    }

    // ── full generation ───────────────────────────────────────────────────

    private GenerationResult buildFull(ReflectionClassInfo meta, TestData data,
                                       String targetPackage, String className,
                                       boolean isDev, TestKitTemplate template) {
        Class<?> type = data.type();
        List<Object> validInstanceParts = valueExtractor.extract(data.base(), type, meta.fields());

        InstantiationWriter instantiation = new InstantiationWriter(meta);
        CreationTestWriter creationWriter = new CreationTestWriter(meta, instantiation, template);
        MemberTestWriter memberWriter = new MemberTestWriter(meta, instantiation, valueExtractor, template);
        MethodTestWriter methodWriter = new MethodTestWriter(meta, instantiation, template);
        ImportCollector imports = buildImports(meta, type, data, validInstanceParts);

        StringBuilder sb = new StringBuilder();
        writeHeader(sb, meta, isDev);
        writePackage(sb, targetPackage);
        writeImports(sb, imports);
        writeClassOpen(sb, meta, className);
        if (projectType.hasValidator()) writeValidatorSetup(sb, template);
        writeValidInstance(sb, meta, validInstanceParts, instantiation, template);
        if (meta.constructorStyle() == ReflectionClassInfo.ConstructorStyle.SETTER) writeSetterHelper(sb, meta);
        if (!meta.utilityClass()) {
            creationWriter.write(sb, data, validInstanceParts, valueExtractor);
            memberWriter.write(sb, type, validInstanceParts, data.validAllPerField());
        }
        methodWriter.write(sb, validInstanceParts, projectType.hasValidator());
        sb.append("}\n");

        return new GenerationResult(className, targetPackage, sb.toString());
    }

    // ── placeholder generation ────────────────────────────────────────────

    private String buildPlaceholder(ReflectionClassInfo meta, String targetPackage, String error,
                                    String className) {
        return "package " + targetPackage + ";\n\n"
                + "// TODO: " + className + "\n"
                + "// Could not generate — DataFactory failed for " + meta.simpleName() + "\n"
                + "// Reason: " + error + "\n"
                + "// Fix the fixture or DataFactory support and regenerate.\n"
                + "//\n"
                + "// class " + className + " {\n"
                + "//     // generation failed — no test content\n"
                + "// }\n";
    }

    // ── helpers ───────────────────────────────────────────────────────────

    private ImportCollector buildImports(ReflectionClassInfo meta, Class<?> type,
                                         TestData data, List<Object> validInstanceParts) {
        ImportCollector ic = new ImportCollector();
        ic.addTypeImport(type);
        ic.addFieldTypeImports(meta.fields());
        ic.addValueImports(validInstanceParts);
        data.violations().forEach(v ->
                ic.addValueImports(valueExtractor.extract(v, type, meta.fields())));
        meta.methods().forEach(m -> ic.addAnnotationImports(m.returnType().annotations()));
        // Add DataValidation import when there are method constraints
        boolean needsDataValidation = meta.methods().stream().anyMatch(m ->
                m.returnType().isConstrained() ||
                        m.parameters().stream().anyMatch(p -> !p.validations().isEmpty()));
        if (needsDataValidation) {
            ic.addRawImport("com.paramichha.utils.DataValidation");
        }
        return ic;
    }

    private void writeHeader(StringBuilder sb, ReflectionClassInfo meta, boolean isDev) {
        sb.append("// Generated by TestKit — do not edit by hand.\n");
        if (isDev) {
            sb.append("// Mode: DEV — full type range, nullable fields.\n");
            sb.append("// Regenerate: TestKit.of(").append(meta.simpleName())
                    .append(".class).withMode(GenerationMode.DEV).generate().writeTo(...)\n");
        } else {
            sb.append("// Regenerate: TestKit.of(").append(meta.simpleName())
                    .append(".class).generate().writeTo(...)\n");
        }
    }

    private void writePackage(StringBuilder sb, String pkg) {
        sb.append("package ").append(pkg).append(";\n\n");
    }

    private void writeImports(StringBuilder sb, ImportCollector imports) {
        imports.collect().forEach(i -> sb.append("import ").append(i).append(";\n"));
        sb.append("\n");
    }

    private void writeClassOpen(StringBuilder sb, ReflectionClassInfo meta, String className) {
        sb.append("@DisplayName(\"").append(meta.simpleName()).append("\")\n");
        sb.append("class ").append(className).append(" {\n\n");
    }

    private void writeValidatorSetup(StringBuilder sb, TestKitTemplate template) {
        sb.append("    private static Validator ").append(template.validatorField).append(";\n\n");
        sb.append("    @BeforeAll\n");
        sb.append("    static void ").append(template.validatorSetup).append("() {\n");
        sb.append("        ").append(template.validatorField)
                .append(" = Validation.buildDefaultValidatorFactory().getValidator();\n");
        sb.append("    }\n\n");
    }

    private void writeValidInstance(StringBuilder sb, ReflectionClassInfo meta,
                                    List<Object> validInstanceParts,
                                    InstantiationWriter instantiation, TestKitTemplate template) {
        if (meta.fields().isEmpty()) return;
        String fieldName = TestNames.toVariable(meta.simpleName());
        sb.append("    ").append(meta.simpleName()).append(" ").append(fieldName).append(" =\n");
        sb.append("            ").append(instantiation.constructorCall(validInstanceParts))
                .append(";\n\n");
    }

    private void writeSetterHelper(StringBuilder sb, ReflectionClassInfo meta) {
        String name = meta.simpleName();
        sb.append("    private static ").append(name).append(" build").append(name).append("(");
        List<ReflectionFieldInfo> fields = meta.fields();
        for (int i = 0; i < fields.size(); i++) {
            if (i > 0) sb.append(", ");
            sb.append(FieldTestWriter.sourceTypeName(fields.get(i).rawType()))
                    .append(" ").append(fields.get(i).name());
        }
        sb.append(") {\n");
        sb.append("        ").append(name).append(" obj = new ").append(name).append("();\n");
        for (ReflectionFieldInfo f : fields) {
            String setter = JavaNames.setterName(f.name());
            sb.append("        obj.").append(setter).append("(").append(f.name()).append(");\n");
        }
        sb.append("        return obj;\n");
        sb.append("    }\n\n");
    }
}