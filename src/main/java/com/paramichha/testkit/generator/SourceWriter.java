package com.paramichha.testkit.generator;

import com.paramichha.testkit.model.ConstructorStyle;
import com.paramichha.testkit.model.FieldInfo;
import com.paramichha.testkit.utils.JavaNames;

import java.util.List;

/**
 * Writes fixed structural sections of a generated test class.
 * Each method appends one section to the provided StringBuilder.
 * No decisions — pure string assembly driven by {@link TestSourceContext}.
 */
final class SourceWriter {

    private SourceWriter() {}

    static void writeHeader(StringBuilder sb, TestSourceContext ctx) {
        sb.append("// Generated by TestKit — do not edit by hand.\n");
        if (ctx.isDev) {
            sb.append("// Mode: DEV — full type range, nullable fields.\n");
            sb.append("// Regenerate: TestKit.of(").append(ctx.simpleName())
                    .append(".class).withMode(GenerationMode.DEV).generateTest().writeTo(...)\n");
        } else {
            sb.append("// Regenerate: TestKit.of(").append(ctx.simpleName())
                    .append(".class).generateTest().writeTo(...)\n");
        }
    }

    static void writePackage(StringBuilder sb, TestSourceContext ctx) {
        sb.append("package ").append(ctx.targetPackage).append(";\n\n");
    }

    static void writeImports(StringBuilder sb, TestSourceContext ctx) {
        ctx.imports.collect().forEach(i -> sb.append("import ").append(i).append(";\n"));
        sb.append("\n");
    }

    static void writeClassOpen(StringBuilder sb, TestSourceContext ctx) {
        sb.append("@DisplayName(\"").append(ctx.simpleName()).append("\")\n");
        sb.append("class ").append(ctx.className).append(" {\n\n");
    }

    static void writeValidatorSetup(StringBuilder sb, TestSourceContext ctx) {
        sb.append("    private static Validator ").append(ctx.template.validatorField).append(";\n\n");
        sb.append("    @BeforeAll\n");
        sb.append("    static void ").append(ctx.template.validatorSetup).append("() {\n");
        sb.append("        ").append(ctx.template.validatorField)
                .append(" = Validation.buildDefaultValidatorFactory().getValidator();\n");
        sb.append("    }\n\n");
    }

    static void writeValidInstance(StringBuilder sb, TestSourceContext ctx) {
        if (ctx.fields().isEmpty()) return;
        sb.append("    ").append(ctx.simpleName()).append(" ").append(ctx.instanceName).append(" =\n");
        sb.append("            ").append(ctx.instantiation.constructorCall(ctx.validParts))
                .append(";\n\n");
    }

    static void writeSetterHelper(StringBuilder sb, TestSourceContext ctx) {
        String          name   = ctx.simpleName();
        List<FieldInfo> fields = ctx.fields();
        sb.append("    private static ").append(name).append(" build").append(name).append("(");
        for (int i = 0; i < fields.size(); i++) {
            if (i > 0) sb.append(", ");
            sb.append(FieldTestWriter.sourceTypeName(fields.get(i).rawType()))
                    .append(" ").append(fields.get(i).name());
        }
        sb.append(") {\n");
        sb.append("        ").append(name).append(" obj = new ").append(name).append("();\n");
        for (FieldInfo f : fields)
            sb.append("        obj.").append(JavaNames.setterName(f.name()))
                    .append("(").append(f.name()).append(");\n");
        sb.append("        return obj;\n");
        sb.append("    }\n\n");
    }
}